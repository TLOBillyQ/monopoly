require("test.bootstrap").install_package_paths()
local check = require("luassert")
local env_lib = require("foundation.env")
local fs_lib = require("foundation.fs")
local feature_stamp = require("acceptance4lua.feature_stamp")
local spec_hash = require("acceptance4lua.spec_hash")

local function _sample_feature(body)
  return body or table.concat({ "Feature: example", "", "Scenario: it works", "  Given a step", "" }, "\n")
end
local function _with_tmp_file(content, fn)
  local tmp_dir = env_lib.make_temp_path("acceptance_feature_stamp_", "")
  fs_lib.remove_path(tmp_dir)
  fs_lib.ensure_dir(tmp_dir)
  local path = tmp_dir .. "/feature.feature"
  local handle = assert(io.open(path, "w"))
  handle:write(content)
  handle:close()
  local ok, err = xpcall(function() fn(path) end, debug.traceback)
  fs_lib.remove_path(tmp_dir)
  if not ok then error(err) end
end

describe("read feature stamp", function()
  it("returns nil when no stamp is present", function()
    check.is_nil(feature_stamp.read_stamp(_sample_feature()))
  end)
  it("reads a stamp at the first line", function()
    check.equal("deadbeef", feature_stamp.read_stamp("# mutation-stamp: sha256=deadbeef\nFeature: x\n"))
  end)
  it("reads a stamp after the first line", function()
    check.equal("cafebabe", feature_stamp.read_stamp("# language: zh-CN\n# mutation-stamp: sha256=cafebabe\n功能: 例子\n"))
  end)
  it("returns nil for a malformed hash", function()
    check.is_nil(feature_stamp.read_stamp("# mutation-stamp: sha256=NOT_HEX\nFeature: x\n"))
  end)
end)
describe("current feature stamp", function()
  it("returns false without a stamp", function()
    check.is_false(feature_stamp.is_stamp_current(_sample_feature()))
  end)
  it("returns true immediately after stamping", function()
    check.is_true(feature_stamp.is_stamp_current(feature_stamp.apply_stamp(_sample_feature())))
  end)
  it("returns false after content changes", function()
    local stamped = feature_stamp.apply_stamp(_sample_feature())
    check.is_false(feature_stamp.is_stamp_current(stamped .. "\n# added comment\n"))
  end)
  it("returns false when the hash does not match", function()
    check.is_false(feature_stamp.is_stamp_current("# mutation-stamp: sha256=" .. string.rep("0", 64) .. "\nFeature: x\n"))
  end)
end)
describe("apply feature stamp", function()
  it("prepends a stamp to an unstamped feature", function()
    local source = _sample_feature()
    local stamped = feature_stamp.apply_stamp(source)
    check.matches("^# mutation%-stamp: sha256=[0-9a-f]+\n", stamped)
    check.matches(source, stamped, 1, true)
  end)
  it("replaces an existing stamp without duplication", function()
    local second_pass = feature_stamp.apply_stamp(feature_stamp.apply_stamp(_sample_feature()))
    local _, stamp_count = second_pass:gsub("mutation%-stamp:", "")
    check.equal(1, stamp_count)
  end)
  it("is idempotent without content edits", function()
    local stamped_once = feature_stamp.apply_stamp(_sample_feature())
    check.equal(stamped_once, feature_stamp.apply_stamp(stamped_once))
  end)
  it("hashes content minus the stamp line", function()
    local source = _sample_feature()
    check.equal(spec_hash.sha256(source), feature_stamp.read_stamp(feature_stamp.apply_stamp(source)))
  end)
end)
describe("apply feature stamp to file", function()
  it("writes a stamp at the top of the target file", function()
    _with_tmp_file(_sample_feature(), function(path)
      local ok, err = feature_stamp.apply_stamp_to_file(path)
      check.is_true(ok)
      check.is_nil(err)
      local content = assert(fs_lib.read_file(path))
      check.matches("^# mutation%-stamp: sha256=[0-9a-f]+\n", content)
      check.is_true(feature_stamp.is_stamp_current(content))
    end)
  end)
  it("replaces an existing file stamp without duplication", function()
    _with_tmp_file(_sample_feature(), function(path)
      check.is_true(feature_stamp.apply_stamp_to_file(path))
      local first = assert(fs_lib.read_file(path))
      check.is_true(feature_stamp.apply_stamp_to_file(path))
      check.equal(first, assert(fs_lib.read_file(path)))
    end)
  end)
end)
