require("test.bootstrap").install_package_paths()
local check = require("luassert")
local env_lib = require("foundation.env")
local fs_lib = require("foundation.fs")
local path_lib = require("foundation.path")
local spec_hash = require("acceptance4lua.spec_hash")

local function _scenario_with(name, value)
  return { name = name, steps = { { keyword = "Given", text = "input is <key>", parameters = { "key" } } }, examples = { { key = value } } }
end
local function _with_tmp(fn)
  local root = env_lib.make_temp_path("acceptance_spec_hash_", "")
  fs_lib.remove_path(root)
  check.truthy(fs_lib.ensure_dir(root))
  local ok, err = xpcall(function() fn(root) end, debug.traceback)
  fs_lib.remove_path(root)
  if not ok then error(err) end
end

describe("acceptance sha256", function()
  it("matches the empty string FIPS 180-4 vector", function()
    check.equal("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855", spec_hash.sha256(""))
  end)
  it("is deterministic across repeated calls", function()
    local first = spec_hash.sha256("the same input every time")
    check.equal(first, spec_hash.sha256("the same input every time"))
  end)
  it("treats nil as empty string", function()
    check.equal(spec_hash.sha256(""), spec_hash.sha256(nil))
  end)
  it("returns 64 hex characters", function()
    check.equal(64, #spec_hash.sha256("any payload"))
    check.matches("^[0-9a-f]+$", spec_hash.sha256("any payload"))
  end)
end)
describe("feature content hash", function()
  it("strips the first mutation stamp before hashing", function()
    local plain = "Feature: example\n\nScenario: it works\n  Given a step\n"
    check.equal(spec_hash.compute_feature_content_hash(plain), spec_hash.compute_feature_content_hash("# mutation-stamp: sha256=deadbeef\n" .. plain))
  end)
  it("strips only the first stamp when more than one is present", function()
    local computed = spec_hash.compute_feature_content_hash("# mutation-stamp: sha256=aaa\nFeature: x\n# mutation-stamp: sha256=bbb\n")
    local without_first = spec_hash.compute_feature_content_hash("# mutation-stamp: sha256=bbb\nFeature: x\n")
    check.equal(spec_hash.sha256("Feature: x\n# mutation-stamp: sha256=bbb\n"), computed)
    check.is_not.equal(computed, without_first)
  end)
  it("matches plain sha256 without a stamp", function()
    local source = "Feature: example\nScenario: noop\n"
    check.equal(spec_hash.sha256(source), spec_hash.compute_feature_content_hash(source))
  end)
end)
describe("background hash", function()
  it("returns a stable hex hash for fixed background", function()
    local background = { { keyword = "Given", text = "a configured project", parameters = {} } }
    local first = spec_hash.compute_background_hash(background)
    check.equal(first, spec_hash.compute_background_hash(background))
    check.equal(64, #first)
  end)
  it("changes when step text changes", function()
    local before = spec_hash.compute_background_hash({ { keyword = "Given", text = "alpha", parameters = {} } })
    local after = spec_hash.compute_background_hash({ { keyword = "Given", text = "beta", parameters = {} } })
    check.is_not.equal(before, after)
  end)
  it("treats nil and empty array alike", function()
    check.equal(spec_hash.compute_background_hash(nil), spec_hash.compute_background_hash({}))
  end)
end)
describe("scenario hash", function()
  it("ignores example key insertion order", function()
    local first = spec_hash.compute_scenario_hash({ name = "two columns", steps = {}, examples = { { alpha = "1", beta = "2" } } })
    local second = spec_hash.compute_scenario_hash({ name = "two columns", steps = {}, examples = { { beta = "2", alpha = "1" } } })
    check.equal(first, second)
  end)
  it("changes when scenario name changes", function()
    check.is_not.equal(spec_hash.compute_scenario_hash(_scenario_with("first", "x")), spec_hash.compute_scenario_hash(_scenario_with("second", "x")))
  end)
  it("changes when example value changes", function()
    check.is_not.equal(spec_hash.compute_scenario_hash(_scenario_with("name", "alpha")), spec_hash.compute_scenario_hash(_scenario_with("name", "beta")))
  end)
  it("changes when example row order changes", function()
    local one = { name = "ordered", steps = {}, examples = { { k = "1" }, { k = "2" } } }
    local two = { name = "ordered", steps = {}, examples = { { k = "2" }, { k = "1" } } }
    check.is_not.equal(spec_hash.compute_scenario_hash(one), spec_hash.compute_scenario_hash(two))
  end)
end)
describe("generated files hash", function()
  it("returns a sha256 prefixed hash", function()
    _with_tmp(function(root)
      local file = path_lib.join_path(root, "generated/test_a.lua")
      check.truthy(fs_lib.write_file(file, "return true\n"))
      local hash = spec_hash.compute_generated_files_hash({ file })
      check.matches("^sha256:[0-9a-f]+$", hash)
      check.equal(71, #hash)
    end)
  end)
  it("changes when generated file content changes", function()
    _with_tmp(function(root)
      local file = path_lib.join_path(root, "generated/test_a.lua")
      check.truthy(fs_lib.write_file(file, "return true\n"))
      local before = spec_hash.compute_generated_files_hash({ file })
      check.truthy(fs_lib.write_file(file, "return false\n"))
      check.is_not.equal(before, spec_hash.compute_generated_files_hash({ file }))
    end)
  end)
end)
