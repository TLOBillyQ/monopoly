if arg then rawset(arg, 0, "tools/packages/luaunit_runner/test/test_spec_sharding.lua") end
require("test.bootstrap").install_package_paths()
local check = require("luassert")
local fs_lib = require("foundation.fs")
local sharding = require("foundation.spec_sharding")
local _TMP_ROOT = "./tmp/spec_sharding_spec"
local function _rm_rf(path) fs_lib.remove_path(path) end
local function _write_file(path, content) assert(fs_lib.write_file(path, content or "")) end
local function _expected_discovered_path(path)
  return require("foundation.path").resolve_path(require("foundation.env").current_dir(), path)
end

describe("spec sharding discover spec files", function()
  before_each(function() _rm_rf(_TMP_ROOT) end)
  after_each(function() _rm_rf(_TMP_ROOT) end)
  it("returns empty list for missing root", function()
    check.same({}, sharding.discover_spec_files(_TMP_ROOT .. "/does_not_exist"))
  end)
  it("returns sorted absolute relative paths under root", function()
    _write_file(_TMP_ROOT .. "/test_b.lua", "it('b', function() end)\n")
    _write_file(_TMP_ROOT .. "/test_a.lua", "it('a', function() end)\n")
    _write_file(_TMP_ROOT .. "/nested/test_c.lua", "it('c', function() end)\n")
    _write_file(_TMP_ROOT .. "/helper_mod.lua", "local M = {}\nreturn M\n")
    local files = sharding.discover_spec_files(_TMP_ROOT)
    check.equal(3, #files, "expected 3 test_*.lua entries, got " .. tostring(#files))
    check.equal(_expected_discovered_path(_TMP_ROOT .. "/nested/test_c.lua"), files[1])
    check.equal(_expected_discovered_path(_TMP_ROOT .. "/test_a.lua"), files[2])
    check.equal(_expected_discovered_path(_TMP_ROOT .. "/test_b.lua"), files[3])
  end)
  -- 命名发现不能被内容嗅探过滤掉动态套件。
  it("discovers named specs without static test defs", function()
    _write_file(_TMP_ROOT .. "/test_dynamic.lua", "local flatten = require(\"x.suite_flatten\")\nTestDyn = flatten({})\n")
    local files = sharding.discover_spec_files(_TMP_ROOT)
    check.equal(1, #files)
    check.equal(_expected_discovered_path(_TMP_ROOT .. "/test_dynamic.lua"), files[1])
  end)
  it("discovers luaunit native spec files", function()
    _write_file(_TMP_ROOT .. "/test_native_colon.lua", "TestFoo = {}\nfunction TestFoo:test_bar(self) end\n")
    _write_file(_TMP_ROOT .. "/test_native_bracket.lua", "TestBar = {}\nTestBar[\"test_中文名\"] = function(self) end\n")
    _write_file(_TMP_ROOT .. "/support_mod.lua", "local M = {}\nreturn M\n")
    local files = sharding.discover_spec_files(_TMP_ROOT)
    check.equal(2, #files, "expected 2 native test_*.lua entries, got " .. tostring(#files))
    check.equal(_expected_discovered_path(_TMP_ROOT .. "/test_native_bracket.lua"), files[1])
    check.equal(_expected_discovered_path(_TMP_ROOT .. "/test_native_colon.lua"), files[2])
  end)
end)

describe("spec sharding file cost", function()
  before_each(function() _rm_rf(_TMP_ROOT) end)
  after_each(function() _rm_rf(_TMP_ROOT) end)
  it("returns 1 for files with no it occurrences", function()
    local path = _TMP_ROOT .. "/test_empty.lua"
    _write_file(path, "describe('only', function() end)\n")
    check.equal(1, sharding.file_cost(path))
  end)
  it("counts each it occurrence", function()
    local path = _TMP_ROOT .. "/test_three.lua"
    _write_file(path, "it('one', function() end)\nit('two', function() end)\nit('three', function() end)\n")
    check.equal(3, sharding.file_cost(path))
  end)
  it("returns 1 for missing path", function()
    check.equal(1, sharding.file_cost(_TMP_ROOT .. "/test_missing.lua"))
  end)
  it("counts luaunit native test definitions", function()
    local path = _TMP_ROOT .. "/test_native.lua"
    _write_file(path, "TestFoo = {}\nfunction TestFoo:test_a(self) end\nfunction TestFoo.test_dot_form(self) end\nTestFoo[\"test_b\"] = function(self) end\nTestFoo[\"test_\" .. case.name] = function(self) case.run() end\n")
    check.equal(4, sharding.file_cost(path))
  end)
end)

describe("spec sharding build lpt lanes", function()
  it("returns a single lane when worker count is 1", function()
    local lanes = sharding.build_lpt_lanes({ "a.lua", "b.lua", "c.lua" }, 1)
    check.equal(1, #lanes)
    check.equal(1, lanes[1].index)
    check.equal(3, #lanes[1].files)
  end)
  it("never emits empty lanes clamps workers to file count", function()
    local lanes = sharding.build_lpt_lanes({ "a.lua", "b.lua" }, 5)
    check.equal(2, #lanes)
    for _, lane in ipairs(lanes) do check.is_true(#lane.files >= 1, "lane " .. tostring(lane.index) .. " is empty") end
  end)
  it("packs by descending cost lpt heaviest file goes to lane 1", function()
    _rm_rf(_TMP_ROOT)
    local heavy, light_a, light_b = _TMP_ROOT .. "/test_heavy.lua", _TMP_ROOT .. "/test_light_a.lua", _TMP_ROOT .. "/test_light_b.lua"
    _write_file(heavy, "it('1', function() end)\nit('2', function() end)\nit('3', function() end)\nit('4', function() end)\n")
    _write_file(light_a, "it('x', function() end)\n")
    _write_file(light_b, "it('y', function() end)\n")
    local lanes = sharding.build_lpt_lanes({ light_a, light_b, heavy }, 2)
    check.equal(2, #lanes)
    check.equal(heavy, lanes[1].files[1])
    check.equal(2, #lanes[2].files)
    _rm_rf(_TMP_ROOT)
  end)
  it("breaks ties by original lane index when costs are equal", function()
    _rm_rf(_TMP_ROOT)
    local a, b = _TMP_ROOT .. "/test_a.lua", _TMP_ROOT .. "/test_b.lua"
    _write_file(a, "it('a', function() end)\n")
    _write_file(b, "it('b', function() end)\n")
    local lanes = sharding.build_lpt_lanes({ a, b }, 2)
    check.equal(a, lanes[1].files[1])
    check.equal(b, lanes[2].files[1])
    _rm_rf(_TMP_ROOT)
  end)
  it("sets total cost on each lane equal to sum of its files costs", function()
    _rm_rf(_TMP_ROOT)
    local a, b = _TMP_ROOT .. "/test_a.lua", _TMP_ROOT .. "/test_b.lua"
    _write_file(a, "it('1', function() end)\nit('2', function() end)\n")
    _write_file(b, "it('x', function() end)\n")
    local lanes = sharding.build_lpt_lanes({ a, b }, 1)
    check.equal(1, #lanes)
    check.equal(3, lanes[1].total_cost)
    _rm_rf(_TMP_ROOT)
  end)
end)

local TEST_ENV = "__EGGY_SHARDING_TEST_ENV_DOES_NOT_EXIST"
describe("spec sharding resolve workers", function()
  it("falls back to default workers when env var unset", function()
    check.equal(3, sharding.resolve_workers(TEST_ENV, 10, 3))
  end)
  it("returns 1 when env var is 1", function()
    check.equal(2, sharding.resolve_workers("PATH", 10, 2))
  end)
  it("clamps result to file count range", function()
    check.equal(2, sharding.resolve_workers(TEST_ENV, 2, 5))
    check.equal(1, sharding.resolve_workers(TEST_ENV, 1, 5))
  end)
  it("returns 1 when file count is 0", function()
    check.equal(1, sharding.resolve_workers(TEST_ENV, 0, 5))
  end)
  it("treats auto or empty as fallback to default", function()
    check.equal(4, sharding.resolve_workers(nil, 10, 4))
  end)
end)
