if arg then rawset(arg, 0, "tools/packages/coverage/test/test_coverage_quiet.lua") end
require("test.bootstrap").install_package_paths()
local check = require("luassert")
local coverage = require("packages.coverage.coverage")

describe("coverage quiet parse args", function()
  it("recognizes quiet flag", function()
    check.is_true(coverage.parse_args({ "--quiet" }).quiet)
  end)
  it("defaults quiet to false", function()
    check.is_false(coverage.parse_args({}).quiet)
  end)
  it("preserves other options when quiet is set", function()
    local opts = coverage.parse_args({ "--quiet", "--out=tmp/cov.md", "--threshold=85", "--profiles=behavior,contract" })
    check.is_true(opts.quiet)
    check.equal("tmp/cov.md", opts.out)
    check.equal(85, opts.threshold)
    check.same({ "behavior", "contract" }, opts.profiles)
  end)
end)

describe("coverage quiet trace", function()
  local captured
  before_each(function()
    captured = {}
    coverage._set_trace_sink_for_tests(function(msg) captured[#captured + 1] = tostring(msg) end)
  end)
  after_each(function()
    coverage._set_trace_sink_for_tests(nil)
  end)
  it("emits when quiet is false", function()
    coverage._trace(false, "Running: luacov")
    check.equal(1, #captured)
    check.equal("Running: luacov", captured[1])
  end)
  it("suppresses when quiet is true", function()
    coverage._trace(true, "Running: luacov")
    check.equal(0, #captured)
  end)
  it("treats nil quiet as not quiet back compat", function()
    coverage._trace(nil, "Running: luacov")
    check.equal(1, #captured)
  end)
end)
