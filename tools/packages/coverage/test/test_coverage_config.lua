if arg then rawset(arg, 0, "tools/packages/coverage/test/test_coverage_config.lua") end
require("test.bootstrap").install_package_paths()
local check = require("luassert")
local config = require("packages.coverage.coverage_config")

-- 配置真源：收集侧、报告侧和 crap luacov adapter 同读本表。
describe("coverage config", function()
  it("returns the luacov config fields", function()
    check.is_table(config.include)
    check.is_table(config.exclude)
    check.is_table(config.includeuntestedfiles)
    check.equal("build/luacov.stats.out", config.statsfile)
    check.equal("build/luacov.report.out", config.reportfile)
    check.is_false(config.deletestats)
    check.is_false(config.runreport)
    check.is_false(config.codefromstrings)
  end)
  it("keeps the six tier include prefixes unanchored", function()
    check.same({ "src/foundation/", "src/rules/", "src/turn/", "src/state/", "src/player/", "src/computer/" }, config.include)
  end)
  it("pins exclude and includeuntestedfiles口径", function()
    check.same({ "src/app/", "src/host/", "src/ui/", "src/config/", "tests/", "test/", "tools/", "vendor/", "/usr/", "/%.luarocks/" }, config.exclude)
    check.same({ "src/foundation", "src/rules", "src/turn", "src/state", "src/player", "src/computer" }, config.includeuntestedfiles)
  end)
end)
